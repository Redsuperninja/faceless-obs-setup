#!/usr/bin/env python3
"""
Makes the alert sounds in assets/sounds/ from scratch (bells, harp-like plucks, a brass-like fanfare).
They are generated by this script, so they are ours to use and share: no licenses to track.

    python make_sounds.py            # writes one .wav per alert kind plus command.wav

Change the notes below and rerun to change the sounds. Sounds are short (under 2 seconds).
"""

import math
import struct
import wave
from pathlib import Path

RATE = 44100
OUT = Path(__file__).resolve().parent.parent / "assets" / "sounds"

# Note frequencies (Hz).
G3, C4, D4, E4, G4, C5, E5, G5, A4, A5, B5, C6, E6, G6, C7 = (
    196.0, 261.63, 293.66, 329.63, 392.0, 523.25, 659.25, 783.99, 440.0, 880.0, 987.77, 1046.5, 1318.5, 1568.0, 2093.0)
D5 = 587.33


class Mix:
    """A mono buffer you add notes to."""

    def __init__(self, seconds):
        self.n = int(RATE * seconds)
        self.buf = [0.0] * self.n

    def _add(self, start, samples):
        i0 = int(start * RATE)
        for k, v in enumerate(samples):
            if i0 + k < self.n:
                self.buf[i0 + k] += v

    def bell(self, freq, start, amp=0.5, decay=3.5, dur=1.4):
        """Metallic bell: partials that are not whole multiples, each fading at its own rate."""
        parts = [(1.0, 1.0, 1.0), (2.76, 0.45, 1.6), (5.4, 0.25, 2.4), (8.93, 0.12, 3.5)]
        n = int(RATE * dur)
        self._add(start, [amp * sum(a * math.exp(-decay * d * t / RATE) * math.sin(2 * math.pi * freq * m * t / RATE)
                                    for m, a, d in parts) / 1.8 for t in range(n)])

    def pluck(self, freq, start, amp=0.4, decay=5.0, dur=1.0):
        """Harp-like: a quick bright start that settles into a soft tone."""
        n = int(RATE * dur)
        self._add(start, [amp * sum((1 / h) * math.exp(-decay * (0.5 + 0.35 * h) * t / RATE)
                                    * math.sin(2 * math.pi * freq * h * t / RATE) for h in (1, 2, 3, 4)) / 1.6
                          for t in range(n)])

    def swell(self, freq, start, dur, amp=0.25, attack=0.09, release=0.35):
        """Brass-like pad: stacked harmonics with a slow attack."""
        n = int(RATE * dur)
        env = lambda t: min(t / (attack * RATE), 1.0) * min(1.0, (n - t) / (release * RATE))  # noqa: E731
        self._add(start, [amp * env(t) * sum((1 / h) * math.sin(2 * math.pi * freq * h * t / RATE) for h in range(1, 7)) / 2.2
                          for t in range(n)])

    def thump(self, start, amp=0.6, f0=110.0, dur=0.35):
        """A low drum hit: a falling pitch that dies away fast."""
        n = int(RATE * dur)
        phase, out = 0.0, []
        for t in range(n):
            phase += 2 * math.pi * (f0 * math.exp(-6 * t / RATE) + 38) / RATE
            out.append(amp * math.exp(-9 * t / RATE) * math.sin(phase))
        self._add(start, out)

    def save(self, name, peak=0.7):
        top = max(1e-9, max(abs(v) for v in self.buf))
        fade_in, fade_out = int(0.003 * RATE), int(0.04 * RATE)
        frames = bytearray()
        for i, v in enumerate(self.buf):
            g = peak / top * min(1.0, i / fade_in) * min(1.0, (self.n - i) / fade_out)
            frames += struct.pack("<h", int(max(-1, min(1, v * g)) * 32767))
        OUT.mkdir(parents=True, exist_ok=True)
        with wave.open(str(OUT / name), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(bytes(frames))


def follow():
    m = Mix(1.3)
    m.bell(E5, 0, 0.5)
    m.bell(A5, 0.13, 0.5)
    return m


def sub():
    m = Mix(1.7)
    for i, f in enumerate((C5, E5, G5, C6)):
        m.pluck(f, i * 0.1)
    m.bell(C6, 0.3, 0.35, decay=2.5, dur=1.3)
    return m


def resub():
    m = Mix(1.8)
    for i, f in enumerate((G4, C5, E5, G5, C6)):
        m.pluck(f, i * 0.09)
    m.bell(G5, 0.36, 0.3, decay=2.5, dur=1.3)
    m.bell(C6, 0.45, 0.35, decay=2.5, dur=1.3)
    return m


def subgift():
    m = Mix(1.2)
    for i, f in enumerate((C6, E6, G6, C7)):
        m.bell(f, i * 0.07, 0.35, decay=6, dur=0.9)
    return m


def giftbomb():
    m = Mix(1.9)
    m.thump(0, 0.7)
    for rep in (0.05, 0.4):
        for i, f in enumerate((C6, E6, G6, C7)):
            m.bell(f, rep + i * 0.07, 0.3, decay=6, dur=0.9)
    return m


def raid():
    m = Mix(2.3)
    m.thump(0, 0.8)
    m.thump(0.5, 0.8)
    for f in (G3, D4, G4):
        m.swell(f, 0, 0.55, 0.3)
    for f in (C4, E4, G4, C5):
        m.swell(f, 0.5, 1.5, 0.3, release=0.7)
    return m


def bits():
    m = Mix(0.9)
    m.bell(B5, 0, 0.5, decay=9, dur=0.6)
    m.bell(E6, 0.09, 0.5, decay=9, dur=0.6)
    return m


def superchat():
    m = Mix(1.9)
    m.bell(A5, 0, 0.55, decay=2.5, dur=1.7)
    m.bell(E6, 0.08, 0.35, decay=3, dur=1.5)
    m.bell(A4, 0, 0.4, decay=2.5, dur=1.7)
    return m


def member():
    m = Mix(2.0)
    for f in (C4, E4, G4, D5):
        m.swell(f, 0, 1.6, 0.22, attack=0.25, release=0.7)
    m.bell(C6, 0.5, 0.35, decay=2.5, dur=1.4)
    return m


def command():
    m = Mix(0.6)
    m.pluck(G5, 0, 0.45, decay=9, dur=0.45)
    return m


SOUNDS = {"follow": follow, "sub": sub, "resub": resub, "subgift": subgift, "giftbomb": giftbomb,
          "raid": raid, "bits": bits, "superchat": superchat, "member": member, "command": command}


def main():
    for name, build in SOUNDS.items():
        build().save(f"{name}.wav")
        print(f"wrote assets/sounds/{name}.wav")


if __name__ == "__main__":
    main()
